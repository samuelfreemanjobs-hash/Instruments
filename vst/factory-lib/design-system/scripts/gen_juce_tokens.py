#!/usr/bin/env python3
"""Generate header-only DesignTokens.h from a theme's tokens.json.

Usage:
    python3 gen_juce_tokens.py --theme disklordz
    python3 gen_juce_tokens.py --all
    python3 gen_juce_tokens.py --all --check   # freshness: exit 1 if stale

Output: vst/factory-lib/gui/generated/<theme_id>/DesignTokens.h
Deterministic: same tokens.json always yields byte-identical headers.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import check_tokens  # noqa: E402
from check_tokens import (  # noqa: E402
    HEX,
    list_themes,
    load_contract,
    load_theme,
    resolve,
    resolve_path,
)

DS_ROOT = Path(__file__).resolve().parents[1]
GUI_GENERATED = DS_ROOT.parent / "gui" / "generated"
IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
# C++ keywords / reserved that collide with role keys (e.g. semantic.active.default).
CPP_KEYWORDS = frozenset(
    {
        "alignas", "alignof", "and", "and_eq", "asm", "auto", "bitand", "bitor",
        "bool", "break", "case", "catch", "char", "char8_t", "char16_t", "char32_t",
        "class", "compl", "concept", "const", "consteval", "constexpr", "constinit",
        "const_cast", "continue", "co_await", "co_return", "co_yield", "decltype",
        "default", "delete", "do", "double", "dynamic_cast", "else", "enum",
        "explicit", "export", "extern", "false", "float", "for", "friend", "goto",
        "if", "inline", "int", "long", "mutable", "namespace", "new", "noexcept",
        "not", "not_eq", "nullptr", "operator", "or", "or_eq", "private",
        "protected", "public", "register", "reinterpret_cast", "requires", "return",
        "short", "signed", "sizeof", "static", "static_assert", "static_cast",
        "struct", "switch", "template", "this", "thread_local", "throw", "true",
        "try", "typedef", "typeid", "typename", "union", "unsigned", "using",
        "virtual", "void", "volatile", "wchar_t", "while", "xor", "xor_eq",
    }
)


def hex_to_argb(hex_color: str) -> str:
    """#RRGGBB -> 0xAARRGGBB (opaque)."""
    if not HEX.match(hex_color):
        raise ValueError(f"not #RRGGBB: {hex_color!r}")
    rr, gg, bb = hex_color[1:3], hex_color[3:5], hex_color[5:7]
    return f"0xff{rr.lower()}{gg.lower()}{bb.lower()}"


def cpp_ident(name: str) -> str:
    """JSON key → valid C++ identifier (kebab/space → camel-ish underscore)."""
    s = name.replace("-", "_").replace(" ", "_")
    if s[0].isdigit():
        s = f"n{s}"
    if not IDENT.match(s):
        raise ValueError(f"cannot form C++ identifier from {name!r}")
    if s in CPP_KEYWORDS:
        s = f"{s}_"
    return s


def cpp_string(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def cpp_float(val: float | int) -> str:
    """C++ float literal that g++ accepts (never `1f` — must be `1.0f`)."""
    f = float(val)
    s = f"{f:.6g}"
    if "." not in s and "e" not in s and "E" not in s:
        s += ".0"
    return s + "f"


def emit_color_tree(lines: list[str], node: dict, tokens: dict, indent: int) -> None:
    pad = " " * indent
    for key, val in node.items():
        ident = cpp_ident(key)
        if isinstance(val, dict):
            lines.append(f"{pad}namespace {ident} {{")
            emit_color_tree(lines, val, tokens, indent + 2)
            lines.append(f"{pad}}}  // namespace {ident}")
        else:
            resolved = resolve(tokens, val)
            argb = hex_to_argb(resolved)
            lines.append(f"{pad}inline constexpr std::uint32_t {ident} = {argb}u;  // {resolved}")


def emit_shadow(name: str, shadow: dict | None, indent: int) -> list[str]:
    pad = " " * indent
    if not shadow:
        return [f"{pad}inline constexpr Shadow {name} {{}};"]
    color = shadow.get("color", "#000000")
    alpha = float(shadow.get("alpha", 0.0))
    oy = int(shadow.get("offsetY", 0))
    blur = int(shadow.get("blur", 0))
    argb = hex_to_argb(color)
    return [
        f"{pad}inline constexpr Shadow {name} {{ {argb}u, {cpp_float(alpha)}, {oy}, {blur} }};"
    ]


def generate_header(tokens: dict, contract: dict) -> str:
    """Return the complete DesignTokens.h source for one theme."""
    theme_id = tokens["id"]
    lines: list[str] = []
    lines.append("// Auto-generated by gen_juce_tokens.py — DO NOT EDIT.")
    lines.append(f"// Theme: {theme_id} v{tokens['version']}  Contract: {tokens['contract']}")
    lines.append("// Regenerated deterministically from themes/<id>/tokens.json")
    lines.append("#pragma once")
    lines.append("")
    lines.append("#include <cstdint>")
    lines.append("")
    lines.append("namespace fds {")
    lines.append("")
    lines.append(f"inline constexpr const char* themeId    = {cpp_string(theme_id)};")
    lines.append(f"inline constexpr const char* themeName  = {cpp_string(tokens['name'])};")
    lines.append(f"inline constexpr const char* brandName  = {cpp_string(tokens['brandName'])};")
    lines.append(f"inline constexpr const char* themeVersion = {cpp_string(tokens['version'])};")
    lines.append(f"inline constexpr const char* contractVersion = {cpp_string(tokens['contract'])};")
    lines.append(f"inline constexpr const char* contractFloor = {cpp_string(contract['contractVersion'])};")
    lines.append("")

    # Semantic colours as fds::color::<group>::<role>
    lines.append("// Semantic role colours (ARGB). Components bind only to these.")
    lines.append("namespace color {")
    emit_color_tree(lines, tokens["semantic"], tokens, 2)
    lines.append("}  // namespace color")
    lines.append("")

    # Typography
    typo = tokens["typography"]
    lines.append("namespace typography {")
    lines.append("  struct Family {")
    lines.append("    const char* name;")
    lines.append("    const char* license;")
    lines.append("    const char* fallback;")
    lines.append("  };")
    lines.append("  struct Style {")
    lines.append("    const char* familyKey;  // \"sans\" | \"mono\"")
    lines.append("    int size;")
    lines.append("    int lineHeight;")
    lines.append("    int weight;")
    lines.append("    float tracking;")
    lines.append("    const char* textCase;")
    lines.append("  };")
    lines.append(f"  inline constexpr int minSize = {int(typo['minSize'])};")
    lines.append("  namespace family {")
    for key, fam in typo["family"].items():
        lines.append(
            f"    inline constexpr Family {cpp_ident(key)} {{ "
            f"{cpp_string(fam['name'])}, {cpp_string(fam['license'])}, {cpp_string(fam['fallback'])} }};"
        )
    lines.append("  }  // namespace family")
    lines.append("  namespace style {")
    for key, st in typo["style"].items():
        lines.append(
            f"    inline constexpr Style {cpp_ident(key)} {{ "
            f"{cpp_string(st['family'])}, {int(st['size'])}, {int(st['lineHeight'])}, "
            f"{int(st['weight'])}, {cpp_float(st['tracking'])}, {cpp_string(st['case'])} }};"
        )
    lines.append("  }  // namespace style")
    lines.append("}  // namespace typography")
    lines.append("")

    # Space
    lines.append("namespace space {")
    for key, val in tokens["space"].items():
        lines.append(f"  inline constexpr int {cpp_ident(str(key))} = {int(val)};")
    lines.append("}  // namespace space")
    lines.append("")

    # Radius
    lines.append("namespace radius {")
    for key, val in tokens["radius"].items():
        lines.append(f"  inline constexpr float {cpp_ident(key)} = {cpp_float(val)};")
    lines.append("}  // namespace radius")
    lines.append("")

    # Stroke
    lines.append("namespace stroke {")
    for key, val in tokens["stroke"].items():
        lines.append(f"  inline constexpr float {cpp_ident(key)} = {cpp_float(val)};")
    lines.append("}  // namespace stroke")
    lines.append("")

    # Elevation
    elev = tokens["elevation"]
    lines.append("namespace elevation {")
    lines.append("  struct Shadow {")
    lines.append("    std::uint32_t color;")
    lines.append("    float alpha;")
    lines.append("    int offsetY;")
    lines.append("    int blur;")
    lines.append("  };")
    lines.append(f"  inline constexpr const char* lightSource = {cpp_string(elev.get('lightSource', 'top'))};")
    well = elev.get("well", {})
    lines.extend(emit_shadow("wellInner", well.get("innerShadow"), 2))
    lines.extend(emit_shadow("wellBottomHighlight", well.get("bottomHighlight"), 2))
    raised = elev.get("raised", {})
    lines.extend(emit_shadow("raisedTopHighlight", raised.get("topHighlight"), 2))
    lines.extend(emit_shadow("raisedDrop", raised.get("dropShadow"), 2))
    overlay = elev.get("overlay", {})
    lines.extend(emit_shadow("overlayDrop", overlay.get("dropShadow"), 2))
    body_grad = raised.get("bodyGradient", {})
    if body_grad:
        # Resolve endpoint colours for convenience
        try:
            from_c = hex_to_argb(resolve_path(tokens, body_grad["from"]))
            to_c = hex_to_argb(resolve_path(tokens, body_grad["to"]))
        except Exception:
            from_c, to_c = "0xff000000u", "0xff000000u"
        lines.append(
            f"  inline constexpr std::uint32_t bodyGradientFrom = {from_c};"
        )
        lines.append(
            f"  inline constexpr std::uint32_t bodyGradientTo = {to_c};"
        )
        lines.append(
            f"  inline constexpr const char* bodyGradientDirection = {cpp_string(body_grad.get('direction', 'top-to-bottom'))};"
        )
    lines.append("}  // namespace elevation")
    lines.append("")

    # Motion
    motion = tokens["motion"]
    lines.append("namespace motion {")
    for key, val in motion.items():
        ident = cpp_ident(key)
        if isinstance(val, (int, float)) and not isinstance(val, bool):
            if isinstance(val, float):
                lines.append(f"  inline constexpr float {ident} = {cpp_float(val)};")
            else:
                lines.append(f"  inline constexpr int {ident} = {int(val)};")
        else:
            lines.append(f"  inline constexpr const char* {ident} = {cpp_string(str(val))};")
    lines.append("}  // namespace motion")
    lines.append("")

    # Size (nested)
    def emit_size(node, indent: int) -> None:
        pad = " " * indent
        for key, val in node.items():
            ident = cpp_ident(str(key))
            if isinstance(val, dict):
                lines.append(f"{pad}namespace {ident} {{")
                emit_size(val, indent + 2)
                lines.append(f"{pad}}}  // namespace {ident}")
            elif isinstance(val, list):
                elems = ", ".join(cpp_float(x) for x in val)
                lines.append(f"{pad}inline constexpr float {ident}[] = {{ {elems} }};")
                lines.append(f"{pad}inline constexpr int {ident}Count = {len(val)};")
            elif isinstance(val, float):
                lines.append(f"{pad}inline constexpr float {ident} = {cpp_float(val)};")
            else:
                lines.append(f"{pad}inline constexpr int {ident} = {int(val)};")

    lines.append("namespace size {")
    emit_size(tokens["size"], 2)
    lines.append("}  // namespace size")
    lines.append("")

    # Interaction
    inter = tokens["interaction"]
    lines.append("namespace interaction {")
    for key, val in inter.items():
        ident = cpp_ident(key)
        if isinstance(val, float):
            lines.append(f"  inline constexpr float {ident} = {cpp_float(val)};")
        elif isinstance(val, int):
            lines.append(f"  inline constexpr int {ident} = {val};")
        else:
            lines.append(f"  inline constexpr const char* {ident} = {cpp_string(str(val))};")
    lines.append("}  // namespace interaction")
    lines.append("")

    # Meter constants
    meter = tokens["meter"]
    lines.append("namespace meter {")
    for key, val in meter.items():
        ident = cpp_ident(key)
        if isinstance(val, list):
            if all(isinstance(x, (int, float)) for x in val):
                elems = ", ".join(cpp_float(x) for x in val)
                lines.append(f"  inline constexpr float {ident}[] = {{ {elems} }};")
                lines.append(f"  inline constexpr int {ident}Count = {len(val)};")
            else:
                lines.append(f"  inline constexpr const char* {ident} = {cpp_string(json.dumps(val))};")
        elif isinstance(val, float):
            lines.append(f"  inline constexpr float {ident} = {cpp_float(val)};")
        elif isinstance(val, int):
            # Prefer float for dB thresholds that are whole numbers
            if ident.endswith("Db") or ident.endswith("Thickness") or ident.endswith("Height") or ident.endswith("Fraction"):
                # keep ints that are clearly counts; dB floors are ints in JSON
                if "Fraction" in ident:
                    lines.append(f"  inline constexpr float {ident} = {cpp_float(val)};")
                else:
                    lines.append(f"  inline constexpr float {ident} = {cpp_float(val)};")
            else:
                lines.append(f"  inline constexpr int {ident} = {val};")
        else:
            lines.append(f"  inline constexpr const char* {ident} = {cpp_string(str(val))};")
    lines.append("}  // namespace meter")
    lines.append("")

    lines.append("}  // namespace fds")
    lines.append("")
    return "\n".join(lines)


def output_path(theme_id: str) -> Path:
    return GUI_GENERATED / theme_id / "DesignTokens.h"


def write_theme(theme_id: str, check_only: bool = False) -> int:
    """Generate or check one theme. Returns 0 on success / fresh."""
    tokens = load_theme(theme_id)
    contract = load_contract()
    # Ensure theme is valid before generating
    errs = check_tokens.check(tokens, contract)
    if errs:
        print(f"FAIL [{theme_id}] tokens invalid ({len(errs)}):", file=sys.stderr)
        for e in errs[:10]:
            print(f"  - {e}", file=sys.stderr)
        return 1
    text = generate_header(tokens, contract)
    path = output_path(theme_id)
    if check_only:
        if not path.exists():
            print(f"FAIL [{theme_id}] missing {path}: run gen_juce_tokens.py --theme {theme_id}", file=sys.stderr)
            return 1
        existing = path.read_text(encoding="utf-8")
        if existing != text:
            print(f"FAIL [{theme_id}] {path.name} is stale: run gen_juce_tokens.py --theme {theme_id}", file=sys.stderr)
            return 1
        print(f"PASS [{theme_id}] generated header fresh")
        return 0
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    print(f"WROTE {path}")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--theme", action="append", help="theme id (repeatable)")
    g.add_argument("--all", action="store_true", help="generate/check every theme")
    ap.add_argument("--check", action="store_true", help="freshness mode: fail if headers are stale/missing")
    args = ap.parse_args()

    themes = list_themes() if args.all else args.theme
    failed = 0
    for theme_id in themes:
        failed |= write_theme(theme_id, check_only=args.check)
    return failed


if __name__ == "__main__":
    sys.exit(main())
