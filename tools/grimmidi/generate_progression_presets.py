#!/usr/bin/env python3
"""Generate vst/GrimMIDI/Source/ProgressionPresetsData.h (100 factory progressions)."""

from __future__ import annotations

import itertools
import random
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "vst/GrimMIDI/Source/ProgressionPresetsData.h"

# Scale: 0=NatMin 1=HarmMin 2=Phrygian 3=PhrygDominant
# Chord: 0-7 matching GrimChordEngine::ChordQuality

NAMES_A = [
    "Ash", "Basement", "Block", "Catacomb", "Coffin", "Drill", "Dusk", "Eclipse",
    "Frozen", "Grim", "Grave", "Hex", "London", "Memphis", "Mist", "Neon", "Night",
    "Nail", "Ritual", "Shadow", "Smoke", "Steel", "Tunnel", "Underground", "Velvet",
    "Void", "Winter", "Afterdark", "Cinematic", "Dominant", "Harmonic", "Phrygian",
]

NAMES_B = ["Loop", "Walk", "Stack", "Gate", "Pull", "Rise", "Pulse", "Shift", "Vision", "Suite"]

PATTERNS = [
    [(1, 4), (6, 4), (1, 4), (6, 4)],
    [(1, 4), (4, 4), (1, 4), (4, 4)],
    [(1, 2), (2, 2), (1, 2), (7, 2), (6, 4)],
    [(6, 4), (7, 4), (1, 4), (5, 4)],
    [(1, 4), (5, 4), (6, 4), (1, 4)],
    [(4, 4), (7, 4), (4, 4), (7, 4)],
    [(1, 8), (6, 4), (7, 4)],
    [(1, 2), (6, 2), (5, 2), (1, 2), (1, 4)],
    [(3, 4), (6, 4), (3, 4), (6, 4)],
    [(1, 4), (2, 4), (1, 4), (2, 4)],
    [(7, 4), (1, 4), (7, 2), (6, 2), (1, 4)],
    [(1, 4), (6, 4), (4, 4), (5, 4)],
]


def steps_literal(steps: list[tuple[int, int]]) -> str:
    cells = []
    for deg, beats in steps:
        cells.append(f"{{{deg}, {beats}}}")
    for _ in range(16 - len(steps)):
        cells.append("{0, 0}")
    inner = ", ".join(cells)
    return f"{{{{{inner}}}}}"


def main() -> None:
    random.seed(0x4752494D)
    presets: list[dict] = []

    # First 36: curated names (hand-tuned scales — bias phrygian dominant on latter half)
    curated = [
        ("Dark Drill i — VI", 140, 0, 1, [(1, 4), (6, 4), (1, 4), (6, 4)]),
        ("Phrygian Trap Loop", 150, 2, 1, [(1, 2), (2, 2), (1, 2), (7, 2), (6, 4)]),
        ("Harmonic Minor Rise", 128, 1, 2, [(6, 4), (7, 4), (1, 4), (5, 4)]),
        ("Underground i — iv", 132, 0, 1, [(1, 4), (4, 4), (1, 4), (4, 4)]),
        ("Grim VI — VII", 145, 0, 1, [(6, 4), (7, 4), (6, 4), (7, 2), (1, 2)]),
        ("Night Phrygian i", 92, 2, 0, [(1, 8), (2, 4), (1, 4)]),
        ("Drill Stack i — V", 148, 0, 2, [(1, 2), (5, 2), (1, 2), (5, 2), (6, 4), (1, 4)]),
        ("Cinematic Minor", 110, 0, 3, [(1, 4), (3, 4), (4, 4), (6, 4)]),
        ("Dominant Pull", 138, 3, 1, [(1, 4), (5, 4), (6, 4), (5, 2), (4, 2)]),
        ("Memphis i — bII color", 125, 2, 1, [(1, 4), (2, 4), (1, 4), (2, 4)]),
    ]
    for name, bpm, scale, chord, pat in curated:
        presets.append(
            {"name": name, "bpm": bpm, "key": 255, "scale": scale, "chord": chord, "steps": pat}
        )

    # Fill to 100 with generated dark progressions (≥40% Phrygian Dominant)
    name_iter = itertools.product(NAMES_A, NAMES_B)
    pat_iter = itertools.cycle(PATTERNS)
    while len(presets) < 100:
        a, b = next(name_iter)
        pat = next(pat_iter)
        scale = 3 if len(presets) % 5 in (0, 1) else random.choice([0, 1, 2, 3])
        chord = random.choice([1, 1, 2, 3, 1, 4, 5])
        bpm = random.choice([118, 124, 128, 132, 140, 144, 148, 92, 150])
        key = 255 if random.random() > 0.15 else random.randint(0, 11)
        presets.append(
            {
                "name": f"{a} {b} {len(presets)+1}",
                "bpm": bpm,
                "key": key,
                "scale": scale,
                "chord": chord,
                "steps": pat,
            }
        )

    assert len(presets) == 100

    lines = [
        "// AUTO-GENERATED by tools/grimmidi/generate_progression_presets.py",
        "#pragma once",
        "",
        "#include \"ProgressionPresets.h\"",
        "",
        "inline constexpr int kProgressionPresetCount = 100;",
        "",
        "inline constexpr std::array<ProgressionPreset, kProgressionPresetCount> kProgressionPresets = {{",
    ]

    for p in presets:
        steps = steps_literal(p["steps"])
        lines.append(
            f'    {{"{p["name"]}", {p["bpm"]}, {p["key"]}, {p["scale"]}, {p["chord"]}, '
            f"{steps}, {len(p['steps'])}}},"
        )

    lines.append("}};")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT} ({len(presets)} presets)")


if __name__ == "__main__":
    main()
