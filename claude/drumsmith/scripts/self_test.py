def write_wav(path, samples, sr, bits=24):
    with wave.open(path, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(bits // 8)
        w.setframerate(sr)
        if bits == 24:
            data = b""
            for s in samples:
                v = int(round(max(-1.0, min(1.0, s)) * 8388607))
                data += struct.pack("<i", v)[:3]
        else:
            data = b"".join(struct.pack("<h", int(round(max(-1.0, min(1.0, s)) * 32767))) for s in samples)
        w.writeframes(data)


def tone(freq, amp, sr, n, fade_ms=3.0, dc=0.0):
    x = [amp * math.sin(2 * math.pi * freq * i / sr) + dc for i in range(n)]
    f = dm.fade_samples(fade_ms, sr)
    for i in range(f):
        g = i / f
        x[i] *= g
        x[n - 1 - i] *= g
    return x


MINUS1 = 10 ** (-1.0 / 20.0)


class TestMath(unittest.TestCase):
    def test_midi_to_hz(self):
        # A4 (69) = 440. 57 is one octave down = 220. 33 is four octaves below 69 minus... 69-33=36 = 3 octaves -> 55. 21 -> 69-21=48 = 4 octaves -> 27.5
        for note, hz in [(69, 440.0), (57, 220.0), (33, 55.0), (21, 27.5)]:
            self.assertAlmostEqual(dm.midi_to_hz(note), hz, places=9)

    def test_cents(self):
        # 110/55 = 2 -> one octave = 1200 cents. One semitone up = 100 cents.
        self.assertAlmostEqual(dm.cents_between(110.0, 55.0), 1200.0, places=9)
        self.assertAlmostEqual(dm.cents_between(440 * 2 ** (1 / 12), 440.0), 100.0, places=9)
        with self.assertRaises(ValueError):
            dm.cents_between(0.0, 55.0)

    def test_dbfs(self):
        # 20*log10(0.5) = -6.0206 ; 20*log10(1) = 0 ; 10^(-1/20) = 0.891250938
        self.assertAlmostEqual(dm.dbfs(0.5), -6.0206, places=4)
        self.assertEqual(dm.dbfs(1.0), 0.0)
        self.assertAlmostEqual(dm.db_to_linear(-1.0), 0.891250938, places=8)
        with self.assertRaises(ValueError):
            dm.dbfs(0.0)

    def test_loop_samples(self):
        # 1 bar @ 74 BPM, 44.1k: 240/74 s * 44100 = 10,584,000/74 = 143,027.027 -> 143027
        self.assertEqual(dm.loop_samples(1, 74, 44100), 143027)
        # 1 bar @ 74 BPM, 48k: 11,520,000/74 = 155,675.676 -> 155676
        self.assertEqual(dm.loop_samples(1, 74, 48000), 155676)
        # 1 bar @ 120 BPM, 48k: 2 s * 48000 = 96000 exactly; 4 bars = 384000
        self.assertEqual(dm.loop_samples(1, 120, 48000), 96000)
        self.assertEqual(dm.loop_samples(4, 120, 48000), 384000)

    def test_loop_halts(self):
        for args in [(0, 120, 48000), (1, 0, 48000), (1, 120, 0)]:
            with self.assertRaises(ValueError):
                dm.loop_samples(*args)

    def test_glide(self):
        # sixteenth = 15000/bpm. 300 ms @ 74 BPM = 300*74/15000 = 1.48. @120 = 300*120/15000 = 2.4
        self.assertAlmostEqual(dm.glide_sixteenths(300, 74), 1.48, places=9)
        self.assertAlmostEqual(dm.glide_sixteenths(300, 120), 2.4, places=9)
        # 1.5 sixteenths @120 = 1.5*125 = 187.5 ms
        self.assertAlmostEqual(dm.glide_ms(1.5, 120), 187.5, places=9)

    def test_fade_and_window(self):
        # 3 ms @ 44100 = 132.3 -> floor 132 (stays under 3 ms). @48000 = 144 exactly.
        self.assertEqual(dm.fade_samples(3, 44100), 132)
        self.assertEqual(dm.fade_samples(3, 48000), 144)
        # 100 ms window at 49 Hz = 4.9 cycles
        self.assertAlmostEqual(dm.cycles_in_window(100, 49), 4.9, places=9)

    def test_cowbell_ratio(self):
        # 800/540 = 40/27 = 1.481481...
        self.assertAlmostEqual(dm.partial_ratio(800, 540), 40.0 / 27.0, places=12)

    def test_pitch_zero_crossing(self):
        # A 55 Hz sine read for 0.5 s must land within 5 cents of 55 Hz.
        sr = 44100
        x = [math.sin(2 * math.pi * 55.0 * i / sr) for i in range(sr // 2)]
        self.assertLess(abs(dm.cents_between(dm.estimate_pitch_zc(x, sr), 55.0)), 5.0)

    def test_true_peak_intersample(self):
        # sin(2*pi*n/4 + pi/4): every sample is +/-0.7071 but the continuous peak is 1.0.
        x = [math.sin(2 * math.pi * n / 4 + math.pi / 4) for n in range(128)]
        self.assertAlmostEqual(max(abs(s) for s in x), 0.70710678, places=6)
        self.assertGreater(dm.true_peak(x), 0.97)
        self.assertLess(dm.true_peak(x), 1.03)


class TestVerify(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.d = self.tmp.name

    def tearDown(self):
        self.tmp.cleanup()

    def status(self, name, check, **kw):
        path = os.path.join(self.d, name)
        rep = vk.verify(path)
        return rep["files"][path][check][0]

    def test_good_file_passes_everything(self):
        p = os.path.join(self.d, "Kick_01.wav")
        write_wav(p, tone(220, MINUS1, 44100, 13230), 44100)
        rep = vk.verify(p)
        self.assertEqual(rep["summary"]["fail"], 0, rep)

    def test_16_bit_fails(self):
        write_wav(os.path.join(self.d, "a.wav"), tone(220, MINUS1, 44100, 13230), 44100, bits=16)
        self.assertEqual(self.status("a.wav", "bit_depth"), "FAIL")

    def test_clipped_fails(self):
        x = [max(-1.0, min(1.0, 3 * s)) for s in tone(110, 1.0, 44100, 13230)]
        write_wav(os.path.join(self.d, "b.wav"), x, 44100)
        self.assertEqual(self.status("b.wav", "no_clipping"), "FAIL")
        self.assertEqual(self.status("b.wav", "peak_ceiling"), "FAIL")

    def test_hard_start_fails_edges(self):
        x = [MINUS1 * math.cos(2 * math.pi * 220 * i / 44100) for i in range(13230)]  # starts at full amplitude
        write_wav(os.path.join(self.d, "c.wav"), x, 44100)
        self.assertEqual(self.status("c.wav", "edges_faded"), "FAIL")

    def test_dc_fails(self):
        write_wav(os.path.join(self.d, "d.wav"), tone(220, 0.5, 44100, 13230, dc=0.05), 44100)
        self.assertEqual(self.status("d.wav", "dc_offset"), "FAIL")

    def test_quiet_file_warns_not_normalized(self):
        write_wav(os.path.join(self.d, "e.wav"), tone(220, 0.2, 44100, 13230), 44100)
        self.assertEqual(self.status("e.wav", "normalized"), "WARN")

    def test_loop_length(self):
        good = os.path.join(self.d, "Loop_120bpm_1bar.wav")
        bad = os.path.join(self.d, "Loop_120bpm_2bar.wav")
        write_wav(good, tone(220, MINUS1, 48000, 96000), 48000)      # 1 bar @120/48k = 96000
        write_wav(bad, tone(220, MINUS1, 48000, 190000), 48000)      # 2 bars would be 192000
        rep = vk.verify(self.d)
        self.assertEqual(rep["files"][good]["loop_length"][0], "PASS")
        self.assertEqual(rep["files"][bad]["loop_length"][0], "FAIL")

    def test_mixed_rates_fail_pack(self):
        write_wav(os.path.join(self.d, "p1.wav"), tone(220, MINUS1, 44100, 13230), 44100)
        write_wav(os.path.join(self.d, "p2.wav"), tone(220, MINUS1, 48000, 14400), 48000)
        self.assertEqual(vk.verify(self.d)["pack"]["uniform_format"][0], "FAIL")

    def test_cli_exit_codes(self):
        write_wav(os.path.join(self.d, "ok.wav"), tone(220, MINUS1, 44100, 13230), 44100)
        self.assertEqual(vk.main([self.d]), 0)
        write_wav(os.path.join(self.d, "bad.wav"), tone(220, MINUS1, 44100, 13230), 44100, bits=16)
        self.assertEqual(vk.main([self.d]), 1)
        with tempfile.TemporaryDirectory() as empty:
            self.assertEqual(vk.main([empty]), 2)


