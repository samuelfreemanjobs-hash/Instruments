#!/usr/bin/env python3
"""Repo-wide agent memory: recall, add, check, index, promote.

Memory lives in disklordz/agents/memory/ as plain markdown so every agent (Cursor, Cloud, CLI)
gets it from a fresh clone. See disklordz/agents/memory/MEMORY.md and SOP-019.

Usage:
    python3 scripts/agent_memory.py recall [keywords...] [--agent ID] [--limit 5]
    python3 scripts/agent_memory.py add --agent ID|shared --kind learning|incident --title T \\
        --area "a, b" --when W --lesson L --do D --evidence E --confidence executed|inspected|assumed
    python3 scripts/agent_memory.py promote L-0003 --agent ID --to docs/disklordz/sops/SOP-VF-06-verify-test.md
    python3 scripts/agent_memory.py index      # regenerate the manifest in MEMORY.md
    python3 scripts/agent_memory.py check      # exit 0 only if memory is well-formed and secret-free
"""
from __future__ import annotations

import argparse
import datetime as dt
import os
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
DEFAULT_ROOT = REPO / "disklordz" / "agents" / "memory"
INDEX_LIMIT = 200
FIELDS = ("date", "area", "when", "lesson", "do", "evidence", "confidence", "status")
CONFIDENCE = {"executed", "inspected", "assumed"}
STATUS_RE = re.compile(r"^(active|retired|promoted:\S+)$")
HEAD_RE = re.compile(r"^### ([LI])-(\d{4}) · (.+)$")
FIELD_RE = re.compile(r"^- \*\*(\w+):\*\* ?(.*)$")
AGENT_RE = re.compile(r"^[a-z][a-z0-9-]*$")
MANIFEST_START = "<!-- manifest:start (generated by scripts/agent_memory.py index) -->"
MANIFEST_END = "<!-- manifest:end -->"
SECRET_PATTERNS = [
    re.compile(r"hooks\.slack\.com/services/T[A-Z0-9]+/B[A-Z0-9]+/[A-Za-z0-9]+"),
    re.compile(r"\bxox[abpr]-[A-Za-z0-9-]{10,}"),
    re.compile(r"\bgh[pousr]_[A-Za-z0-9]{30,}"),
    re.compile(r"\bsk_(live|test)_[A-Za-z0-9]{16,}"),
    re.compile(r"\bAKIA[0-9A-Z]{16}\b"),
    re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----"),
    re.compile(r"\beyJ[A-Za-z0-9_-]{20,}\.[A-Za-z0-9_-]{20,}\.[A-Za-z0-9_-]{10,}"),
]
STOP = set("a an the and or of to in on for with is are be it this that from as at by not no".split())


def root() -> Path:
    return Path(os.environ.get("AGENT_MEMORY_ROOT", DEFAULT_ROOT))


@dataclass
class Entry:
    kind: str  # L or I
    num: int
    title: str
    fields: dict[str, str] = field(default_factory=dict)
    file: Path | None = None

    @property
    def ident(self) -> str:
        return f"{self.kind}-{self.num:04d}"

    def render(self) -> str:
        lines = [f"### {self.ident} · {self.title}"]
        lines += [f"- **{k}:** {self.fields.get(k, '')}" for k in FIELDS]
        return "\n".join(lines) + "\n"


def memory_file(agent: str, kind: str) -> Path:
    return root() / f"{agent}_{'learnings' if kind == 'L' else 'incidents'}.md"


def parse(path: Path) -> list[Entry]:
    entries: list[Entry] = []
    cur: Entry | None = None
    for line in path.read_text(encoding="utf-8").splitlines():
        m = HEAD_RE.match(line)
        if m:
            cur = Entry(m.group(1), int(m.group(2)), m.group(3).strip(), file=path)
            entries.append(cur)
            continue
        f = FIELD_RE.match(line)
        if cur and f:
            cur.fields[f.group(1)] = f.group(2).strip()
    return entries


def all_files() -> list[Path]:
    return sorted(p for p in root().glob("*_*.md") if p.name != "MEMORY.md")


def all_entries() -> list[Entry]:
    return [e for p in all_files() for e in parse(p)]


def tokens(text: str) -> set[str]:
    return {t for t in re.findall(r"[a-z0-9][a-z0-9_.+-]*", text.lower()) if t not in STOP and len(t) > 1}


def find_secrets(text: str) -> list[str]:
    return [m.group(0)[:24] + "…" for pat in SECRET_PATTERNS for m in pat.finditer(text)]


# ---------------- commands ----------------

def recall(query: list[str], agent: str | None, limit: int) -> str:
    idx = root() / "MEMORY.md"
    out = []
    if idx.exists():
        text = idx.read_text(encoding="utf-8")
        hot = re.search(r"## Always load\n(.*?)(\n## |\Z)", text, re.S)
        if hot:
            out.append("## Always load\n" + hot.group(1).strip())
    q = tokens(" ".join(query))
    scope = [e for e in all_entries()
             if e.fields.get("status", "active") != "retired"
             and (agent is None or e.file.name.startswith(("shared_", f"{agent}_")))]
    if q:
        scored = []
        for e in scope:
            hay = tokens(" ".join([e.title, e.fields.get("area", ""), e.fields.get("when", ""), e.fields.get("lesson", "")]))
            s = len(q & hay) + 2 * len(q & tokens(e.title + " " + e.fields.get("area", "")))
            if s:
                scored.append((s, e))
        scored.sort(key=lambda x: (-x[0], x[1].file.name, x[1].num))
        picks = [e for _, e in scored[:limit]]
        out.append(f"## Matches for: {' '.join(query)}")
        out += [f"[{e.file.name}] " + e.render() for e in picks] or ["(no matching entries)"]
    return "\n\n".join(out)


def add(agent: str, kind: str, title: str, values: dict[str, str]) -> Entry:
    if agent != "shared" and not AGENT_RE.match(agent):
        raise ValueError(f"agent id {agent!r} must be lowercase-kebab or 'shared'")
    k = "L" if kind == "learning" else "I"
    vals = {f: (values.get(f) or "").strip() for f in FIELDS}
    vals["date"] = vals["date"] or dt.date.today().isoformat()
    vals["status"] = vals["status"] or "active"
    missing = [f for f in FIELDS if not vals[f]]
    if missing:
        raise ValueError(f"missing fields: {', '.join(missing)}")
    if vals["confidence"] not in CONFIDENCE:
        raise ValueError(f"confidence must be one of {sorted(CONFIDENCE)}")
    blob = title + " " + " ".join(vals.values())
    if find_secrets(blob):
        raise ValueError("entry looks like it contains a secret; remove it")
    path = memory_file(agent, k)
    existing = parse(path) if path.exists() else []
    t_new = tokens(title)
    for e in all_entries():
        t_old = tokens(e.title)
        if t_new and t_old and len(t_new & t_old) / len(t_new | t_old) >= 0.8:
            raise ValueError(f"duplicate of {e.file.name} {e.ident} '{e.title}': update that entry instead")
    entry = Entry(k, max([e.num for e in existing], default=0) + 1, title.strip(), vals, path)
    if not path.exists():
        label = "learnings (validated lessons)" if k == "L" else "incidents (dated problems and fixes)"
        path.write_text(f"# {agent} — {label}\n\nFormat and rules: [MEMORY.md](MEMORY.md).\n\n", encoding="utf-8")
    with path.open("a", encoding="utf-8", newline="\n") as f:
        f.write("\n" + entry.render())
    write_index()
    return entry


def promote(ident: str, agent: str, target: str) -> Entry:
    kind = ident[0]
    path = memory_file(agent, kind)
    text = path.read_text(encoding="utf-8")
    entries = {e.ident: e for e in parse(path)}
    if ident not in entries:
        raise KeyError(f"{ident} not in {path.name}")
    block = re.compile(rf"(### {re.escape(ident)} · .*?\n(?:- \*\*\w+:\*\*.*\n)*?)- \*\*status:\*\* .*\n")
    new, n = block.subn(lambda m: m.group(1) + f"- **status:** promoted:{target}\n", text, count=1)
    if n != 1:
        raise RuntimeError(f"could not update status of {ident}")
    path.write_text(new, encoding="utf-8", newline="\n")
    write_index()
    return parse(path)[[e.ident for e in parse(path)].index(ident)]


def manifest() -> str:
    rows = ["| File | Entries | Active | Promoted |", "|------|---------|--------|----------|"]
    for p in all_files():
        es = parse(p)
        act = sum(e.fields.get("status") == "active" for e in es)
        pro = sum(e.fields.get("status", "").startswith("promoted:") for e in es)
        rows.append(f"| [{p.name}]({p.name}) | {len(es)} | {act} | {pro} |")
    return "\n".join(rows)


def write_index() -> None:
    idx = root() / "MEMORY.md"
    text = idx.read_text(encoding="utf-8")
    block = f"{MANIFEST_START}\n{manifest()}\n{MANIFEST_END}"
    pat = re.compile(re.escape(MANIFEST_START) + r".*?" + re.escape(MANIFEST_END), re.S)
    text = pat.sub(lambda _: block, text) if pat.search(text) else text.rstrip() + "\n\n" + block + "\n"
    idx.write_text(text, encoding="utf-8", newline="\n")


def check() -> list[str]:
    errors: list[str] = []
    idx = root() / "MEMORY.md"
    if not idx.exists():
        return ["MEMORY.md missing"]
    itext = idx.read_text(encoding="utf-8")
    if len(itext.splitlines()) > INDEX_LIMIT:
        errors.append(f"MEMORY.md has {len(itext.splitlines())} lines (limit {INDEX_LIMIT}): move detail into entry files")
    m = re.search(re.escape(MANIFEST_START) + r"\n(.*?)\n" + re.escape(MANIFEST_END), itext, re.S)
    if not m or m.group(1) != manifest():
        errors.append("MEMORY.md manifest is stale: run scripts/agent_memory.py index")
    for p in [idx, *all_files()]:
        for s in find_secrets(p.read_text(encoding="utf-8")):
            errors.append(f"{p.name}: possible secret {s}")
    known = set()
    for p in all_files():
        es = parse(p)
        expected_kind = "L" if p.name.endswith("_learnings.md") else "I" if p.name.endswith("_incidents.md") else None
        if expected_kind is None:
            errors.append(f"{p.name}: name must end in _learnings.md or _incidents.md")
        nums = [e.num for e in es]
        if nums != list(range(1, len(es) + 1)):
            errors.append(f"{p.name}: ids must run 1..n without gaps or repeats (got {nums})")
        for e in es:
            known.add(f"{p.stem}:{e.ident}")
            if expected_kind and e.kind != expected_kind:
                errors.append(f"{p.name} {e.ident}: wrong kind for this file")
            miss = [f for f in FIELDS if not e.fields.get(f)]
            if miss:
                errors.append(f"{p.name} {e.ident}: missing {', '.join(miss)}")
            if e.fields.get("confidence") and e.fields["confidence"] not in CONFIDENCE:
                errors.append(f"{p.name} {e.ident}: confidence {e.fields['confidence']!r}")
            if e.fields.get("status") and not STATUS_RE.match(e.fields["status"]):
                errors.append(f"{p.name} {e.ident}: status {e.fields['status']!r}")
            elif e.fields.get("status", "").startswith("promoted:"):
                target = e.fields["status"].split(":", 1)[1]
                if not (REPO / target).exists():
                    errors.append(f"{p.name} {e.ident}: promoted target {target} does not exist")
            if e.fields.get("date") and not re.match(r"^\d{4}-\d{2}-\d{2}$", e.fields["date"]):
                errors.append(f"{p.name} {e.ident}: date must be YYYY-MM-DD")
    for ref in re.findall(r"\b([a-z][a-z0-9-]*_(?:learnings|incidents)):([LI]-\d{4})\b", itext):
        if f"{ref[0]}:{ref[1]}" not in known:
            errors.append(f"MEMORY.md references unknown entry {ref[0]}:{ref[1]}")
    return errors


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("recall")
    r.add_argument("query", nargs="*")
    r.add_argument("--agent")
    r.add_argument("--limit", type=int, default=5)
    a = sub.add_parser("add")
    a.add_argument("--agent", required=True)
    a.add_argument("--kind", choices=["learning", "incident"], required=True)
    a.add_argument("--title", required=True)
    for f in FIELDS:
        a.add_argument(f"--{f}", default="")
    pr = sub.add_parser("promote")
    pr.add_argument("ident")
    pr.add_argument("--agent", required=True)
    pr.add_argument("--to", required=True)
    sub.add_parser("index")
    sub.add_parser("check")
    args = ap.parse_args(argv)
    try:
        if args.cmd == "recall":
            print(recall(args.query, args.agent, args.limit))
        elif args.cmd == "add":
            e = add(args.agent, args.kind, args.title, {f: getattr(args, f) for f in FIELDS})
            print(f"added {e.file.name} {e.ident} · {e.title}")
        elif args.cmd == "promote":
            e = promote(args.ident, args.agent, args.to)
            print(f"{e.ident} -> {e.fields['status']}")
        elif args.cmd == "index":
            write_index()
            print("index updated")
        elif args.cmd == "check":
            errs = check()
            for e in errs:
                print(f"FAIL {e}", file=sys.stderr)
            print(f"{'FAIL' if errs else 'PASS'} memory ({len(all_entries())} entries in {len(all_files())} files)")
            return 1 if errs else 0
    except (ValueError, KeyError, RuntimeError, FileNotFoundError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
